import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { expect, it } from "vitest";

it("binds only paid guest purchases, preserves identities/Admins/data and rejects duplicate ownership", async () => {
  const db = new PGlite();
  const user = "00000000-0000-0000-0000-000000000001";
  const admin = "00000000-0000-0000-0000-000000000002";
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key,email text,encrypted_password text);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
      grant usage on schema auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;
      create table client_access_codes(id bigint generated by default as identity primary key,email text unique,code text,client_name text,company_name text,
        role text default 'user',is_admin boolean default false,is_active boolean default true,complimentary_access boolean default false,auth_user_id uuid);
      create table subscriptions(user_id bigint,plan text,status text,access_granted boolean,current_period_end timestamptz,
        provider text default 'stripe',stripe_checkout_session_id text,stripe_subscription_id text);
      create table brand_projects(id bigint primary key,account_id bigint);
      create table user_answers(id bigint primary key,answer text);
      alter table user_answers enable row level security;
      create policy fixture_own on user_answers for all to authenticated using(true) with check(true);
      grant select on user_answers to authenticated;
      insert into user_answers values(1,'réponse intacte');
      insert into auth.users values('${admin}','marine@example.test','original-password-hash');
      insert into client_access_codes(email,role,is_admin,auth_user_id) values('marine@example.test','admin',true,'${admin}');
    `);
    for (const migration of ["20261113180000_account_lifetime.sql", "20261117120000_tyash_annual_payments.sql", "20261117160000_tyash_guest_checkout.sql", "20261119170000_annual_price_52.sql", "20261120120000_annual_free_checkout.sql"]) {
      await db.exec(readFileSync(new URL(`../supabase/migrations/${migration}`, import.meta.url), "utf8"));
    }
    const reserve = async (email: string, owner = "a".repeat(64)) => (await db.query<{ id: string }>("select * from reserve_guest_annual_checkout($1,$2,'price55',false,'{}')",[email,owner])).rows[0];
    const order = await reserve("guest@example.test");
    expect((await db.query("select amount from annual_payments where id=$1", [order.id])).rows[0]).toEqual({ amount: 5200 });
    const freeOrder = await reserve("free@example.test");
    await db.query("update annual_payments set session_id='cs_free' where id=$1", [freeOrder.id]);
    await db.query("select apply_annual_payment('cs_free',null,null,'evt_free',now()-interval '1 second',false)");
    const free = (await db.query<{ paid_at: Date; expires_at: Date }>("select paid_at,expires_at from annual_payments where id=$1", [freeOrder.id])).rows[0];
    expect(free.expires_at.getTime() - free.paid_at.getTime()).toBe(365 * 86400000);
    await db.query("select apply_annual_payment('cs_free',null,null,'evt_free_replay',now(),false)");
    expect((await db.query("select paid_at,expires_at from annual_payments where id=$1", [freeOrder.id])).rows[0]).toEqual(free);
    expect((await reserve("guest@example.test")).id).toBe(order.id);
    // A different browser cannot infer that this email already has a purchase.
    const secondBrowserOrder = await reserve("guest@example.test","b".repeat(64));
    expect(secondBrowserOrder.id).not.toBe(order.id);
    expect((await db.query("select * from auth.users")).rows).toHaveLength(1);
    expect((await db.query("select * from client_access_codes")).rows).toHaveLength(1);
    await db.exec(`insert into auth.users values('${user}','guest@example.test','')`);
    await expect(db.query("select bind_guest_annual_payment($1,$2)",[order.id,user])).rejects.toThrow(/Paid purchase required/);
    const pay = async (id: string, session: string) => {
      await db.query("update annual_payments set session_id=$1 where id=$2",[session,id]);
      await db.query("select apply_annual_payment($1,$2,null,$3,now()-interval '1 second',false)",[session,`pi_${session}`,`evt_${session}`]);
    };
    await pay(order.id,"cs_guest");
    await expect(db.query("select bind_guest_annual_payment($1,$2)",[order.id,admin])).rejects.toThrow(/Identity mismatch/);
    expect((await db.query("select bind_guest_annual_payment($1,$2) as state",[order.id,user])).rows[0]).toEqual({ state: "ready" });
    const account = (await db.query<{ id: number; access_started_at: Date; access_expires_at: Date; is_admin: boolean }>("select * from client_access_codes where email='guest@example.test'")).rows[0];
    expect(account.is_admin).toBe(false);
    expect(account.access_expires_at.getTime()-account.access_started_at.getTime()).toBe(365*86400000);
    await db.query("select bind_guest_annual_payment($1,$2)",[order.id,user]);
    await db.query("select apply_annual_payment('cs_guest','pi_cs_guest',null,'evt_replay',now(),false)");
    expect((await db.query("select * from client_access_codes where email='guest@example.test'")).rows[0]).toEqual(account);
    await pay(secondBrowserOrder.id,"cs_duplicate");
    expect((await db.query("select bind_guest_annual_payment($1,$2) as state",[secondBrowserOrder.id,user])).rows[0]).toEqual({ state: "existing_access" });
    expect((await db.query("select * from client_access_codes where email='guest@example.test'")).rows[0]).toEqual(account);
    const unpaidUser = "00000000-0000-0000-0000-000000000003";
    await db.exec(`insert into auth.users values('${unpaidUser}','unpaid@example.test','retained-hash');
      insert into client_access_codes(email,auth_user_id,annual_access_required,client_name,company_name)
      values('unpaid@example.test','${unpaidUser}',true,'Camille','Entreprise conservée')`);
    const unpaidOrder = await reserve("unpaid@example.test"); await pay(unpaidOrder.id,"cs_unpaid");
    await db.query("select bind_guest_annual_payment($1,$2)",[unpaidOrder.id,unpaidUser]);
    expect((await db.query("select client_name,company_name,is_admin,role from client_access_codes where email='unpaid@example.test'")).rows[0])
      .toEqual({ client_name: "Camille", company_name: "Entreprise conservée", is_admin: false, role: "user" });
    expect((await db.query("select activation_required from annual_payments where id=$1",[unpaidOrder.id])).rows[0]).toEqual({ activation_required: false });
    expect((await db.query("select encrypted_password from auth.users where id=$1",[unpaidUser])).rows[0]).toEqual({ encrypted_password: "retained-hash" });
    const adminBefore = (await db.query("select * from client_access_codes where email='marine@example.test'")).rows[0];
    const adminOrder = await reserve("marine@example.test"); await pay(adminOrder.id,"cs_admin");
    expect((await db.query("select bind_guest_annual_payment($1,$2) as state",[adminOrder.id,admin])).rows[0]).toEqual({ state: "existing_access" });
    expect((await db.query("select * from client_access_codes where email='marine@example.test'")).rows[0]).toEqual(adminBefore);
    expect((await db.query("select encrypted_password from auth.users where id=$1",[admin])).rows[0]).toEqual({ encrypted_password: "original-password-hash" });
    await db.exec(`set role authenticated; set test.uid='${user}'`);
    expect((await db.query("select * from user_answers")).rows).toHaveLength(1);
    await expect(db.query("select * from annual_activation_grants")).rejects.toThrow(/permission denied/);
    await expect(db.query("select * from annual_auth_identity('marine@example.test')")).rejects.toThrow(/permission denied/);
    await expect(db.query("select * from reserve_guest_annual_checkout('other@example.test',repeat('c',64),'price55',false,'{}')")).rejects.toThrow(/permission denied/);
    await db.exec("reset role; update annual_payments set paid_at=now()-interval '366 days',expires_at=now()-interval '1 day' where session_id='cs_guest'");
    await db.exec("set role authenticated");
    expect((await db.query("select * from user_answers")).rows).toHaveLength(0);
    await db.exec("reset role");
    expect((await db.query("select * from user_answers")).rows).toEqual([{ id: 1, answer: "réponse intacte" }]);
    expect((await db.query("select * from claim_expired_accounts(10)")).rows).toHaveLength(0);
  } finally { await db.close(); }
},30000);
