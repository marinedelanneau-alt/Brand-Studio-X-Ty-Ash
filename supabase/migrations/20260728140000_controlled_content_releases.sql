create or replace function public.upsert_admin_preview_answers(
  target_release_id uuid,
  module_key text,
  module_answers jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor uuid := auth.uid();
  account_id bigint;
begin
  if not public.is_admin(actor) then raise exception 'admin role required'; end if;
  if nullif(btrim(module_key), '') is null then raise exception 'module key required'; end if;
  if jsonb_typeof(module_answers) <> 'object' then raise exception 'module answers must be an object'; end if;
