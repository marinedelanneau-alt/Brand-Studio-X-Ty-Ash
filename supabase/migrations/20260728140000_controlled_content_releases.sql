create or replace function public.publish_content_release(
  draft_release_id uuid,
  release_notes text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor uuid := auth.uid();
  state_row public.application_release_state%rowtype;
  target public.content_releases%rowtype;
begin
  if not public.is_admin(actor) then raise exception 'admin role required'; end if;
  if nullif(btrim(release_notes), '') is null then raise exception 'release notes required'; end if;

  select * into state_row from public.application_release_state where id = 1 for update;
  select * into target from public.content_releases where id = draft_release_id for update;
  if target.id is null or target.status <> 'ready' then
    raise exception 'release must be ready before publication';
  end if;
  if state_row.current_draft_release_id <> target.id then
    raise exception 'only the current draft can be published';
  end if;
  if state_row.published_release_id is null then
    raise exception 'published release reference is missing';
  end if;

  update public.content_releases
  set status = 'archived', updated_at = now()
  where id = state_row.published_release_id and status = 'published';
  if not found then raise exception 'current published release not found'; end if;

  update public.content_releases
  set status = 'published',
      notes = btrim(release_notes),
      published_at = now(),
      published_by = actor,
      updated_at = now()
  where id = target.id and status = 'ready';
  if not found then raise exception 'publication conflict'; end if;

  update public.application_release_state
  set published_release_id = target.id,
      current_draft_release_id = null,
      updated_at = now(),
      updated_by = actor
  where id = 1;

  insert into public.admin_audit_logs(
    admin_user_id, action_type, entity_type, entity_id, release_id, metadata
  ) values (
    actor, 'release_published', 'content_release', target.id::text, target.id,
    jsonb_build_object('previous_release_id', state_row.published_release_id, 'notes', btrim(release_notes))
  );
end;
$$;

