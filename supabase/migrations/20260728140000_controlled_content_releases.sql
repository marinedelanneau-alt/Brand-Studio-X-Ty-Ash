-- Bootstrap V1 from the exact legacy content visible at migration time. This
-- copies data into new tables; it does not alter the legacy production source.
do $$
declare
  initial_release_id uuid;
  initial_modules jsonb;
begin
  if not exists (select 1 from public.application_release_state where id = 1) then
    select coalesce(
      jsonb_agg(module_snapshot order by module_position),
      '[]'::jsonb
    ) into initial_modules
    from (
      select
        module.position as module_position,
        jsonb_build_object(
          'stableKey', 'module_' || module.id,
          'legacyId', module.id,
          'title', module.title,
          'position', module.position,
          'isPublished', module.is_published,
          'videoUrl', coalesce(module.video_url, ''),
          'audioUrl', coalesce(module.audio_url, ''),
          'audioTranscript', coalesce(module.audio_transcript, ''),
          'contentHtml', coalesce(module.content_html, ''),
          'submodules', coalesce((
            select jsonb_agg(
              jsonb_build_object(
                'stableKey', 'submodule_' || submodule.id,
                'legacyId', submodule.id,
                'title', submodule.title,
                'position', submodule.position,
                'videoUrl', coalesce(submodule.video_url, ''),
                'audioUrl', coalesce(submodule.audio_url, ''),
                'audioTranscript', coalesce(submodule.audio_transcript, ''),
                'contentHtml', coalesce(submodule.content_html, ''),
                'exercises', coalesce((
                  select jsonb_agg(
                    jsonb_build_object(
                      'stableKey', 'exercise_' || exercise.id,
                      'legacyId', exercise.id,
                      'position', exercise.position,
                      'type', exercise.type,
                      'question', exercise.question,
                      'options', coalesce(exercise.options, '[]'::jsonb),
                      'explanation', coalesce(exercise.explanation, ''),
                      'answerPlaceholder', coalesce(exercise.answer_placeholder, ''),
                      'audioUrl', coalesce(exercise.audio_url, ''),
                      'audioTranscript', coalesce(exercise.audio_transcript, '')
                    ) order by exercise.position
                  )
                  from public.module_exercises exercise
                  where exercise.module_id = module.id
                    and exercise.submodule_id = submodule.id
                ), '[]'::jsonb)
              ) order by submodule.position
            )
            from public.brand_submodules submodule
            where submodule.module_id = module.id
          ), '[]'::jsonb)
        ) as module_snapshot
      from public.brand_modules module
      where module.is_published = true
    ) snapshot_rows;

    insert into public.content_releases(name, status, notes, published_at)
    values ('Version publiée initiale', 'published', 'Import non destructif du contenu historique', now())
    returning id into initial_release_id;

    insert into public.content_release_snapshots(release_id, schema_version, modules)
    values (initial_release_id, 1, initial_modules);
    insert into public.application_release_state(id, published_release_id)
    values (1, initial_release_id);
  end if;
end;
$$;

