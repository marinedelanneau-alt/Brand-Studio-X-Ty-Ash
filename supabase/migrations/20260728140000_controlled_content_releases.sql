    account_id, target_release_id, 'new_user',
    jsonb_build_object(module_key, module_answers)
  )
  on conflict (admin_account_id, release_id, mode)
  do update set
    answers = public.admin_preview_answer_sets.answers
      || jsonb_build_object(module_key, module_answers),
    updated_at = now();
