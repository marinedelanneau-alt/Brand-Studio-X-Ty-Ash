create or replace function public.guard_published_release_content()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  guarded_release_id uuid;
begin
  guarded_release_id := coalesce(new.release_id, old.release_id);
  if exists (
    select 1 from public.content_releases
    where id = guarded_release_id and status in ('published', 'archived')
  ) then
    raise exception 'published and archived release content is immutable';
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

